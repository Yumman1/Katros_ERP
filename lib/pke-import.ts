export function normalizePkeReferences(refs:Record<string,string>) {
  return {...refs,"Phytosanitary certificate":refs["Pakistan import permit"]??""};
}
export function pkeRemaining(quantity:number,received:number){return Math.max(0,quantity-received);}

export function pkeReceiptProgress(total:number,prior:number,quantity:number){
  if(![total,prior,quantity].every(Number.isFinite)||total<=0||prior<0||quantity<=0)throw new Error("Enter a positive received quantity");
  if(quantity>pkeRemaining(total,prior)+0.000001)throw new Error("Gate-in exceeds the supplier purchase's remaining quantity");
  const received=prior+quantity,open=pkeRemaining(total,received);
  return {received,open,closed:open<=0.000001};
}

export type PkeLcBypass = {
 id:string;lcId:string;lcSnapshot:PkeLc;requirements:string;reason:string;
 status:"PENDING"|"APPROVED"|"REJECTED";
 requestedById:string;requestedBy:string;requestedAt:string;
 reviewedById?:string;reviewedBy?:string;reviewedAt?:string;reviewNote?:string;
};
export function lcBypassBlocksPayment(payload:PkeImportPayload):boolean {
 const latest=new Map<string,PkeLcBypass>();
 for(const request of payload.bypasses??[])latest.set(request.lcId,request);
 return [...latest.values()].some(request=>request.status!=="APPROVED" || JSON.stringify(request.lcSnapshot)!==JSON.stringify(payload.lcs?.find(l=>l.id===request.lcId)));
}

export function canApprovePkeLcBypass(user:{role:string;isHead:boolean;disabled?:boolean}):boolean {
 return user.role==="EXECUTION"&&user.isHead&&!user.disabled;
}
