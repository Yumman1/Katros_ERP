/** Integration test: only an empty disposable local database is accepted. */
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {prisma} from '../server/db';
import {createInternalPayment,internalPaymentRows,entityCounterparty} from '../server/finance/internal-payments';
import {approveVoucher,listVouchers,excessAdvanceQueue,resolveExcessAdvance,rejectVoucher} from '../server/finance/vouchers';
import {createInternationalPurchase} from '../server/finance/international-purchase';
import {getLockedContracts,refreshContract} from '../server/execution/contracts';
import {sesameBook} from '../server/execution/sesame-ownership';
import {tripartyGateTrades} from '../server/execution/sesame-export';
import {bookedPakistanSaleKgAtWarehouse} from '../server/execution/sesame-sale-reservation';
import {deskSide} from '../lib/sesame-entity';

async function main(){
 const url=new URL(process.env.POSTGRES_PRISMA_URL!);
 assert.equal(url.hostname,'127.0.0.1');assert.equal(url.port,'55433');assert.equal(await prisma.user.count(),0);
 const user=await prisma.user.create({data:{name:'Internal Trader',email:'internal@example.invalid',role:'TRADER',passwordHash:'test'}});
 const cp=await entityCounterparty(prisma,'FZCO',user.id);
 const commodity=await prisma.commodity.create({data:{name:'Sesame',code:'SES',unit:'MT',category:'OILSEEDS',createdById:user.id}});
 const params={tradingEntity:'Kastros PAK',internalCounterpartyEntity:'FZCO',executionFxPkrPerUsd:280,sesameType:'Raw',warehouseSelections:'Test warehouse'};
 const trade=await prisma.trade.create({data:{tradeRef:'INTERNAL-TEST',tradeDate:new Date(),deliveryStart:new Date(),deliveryEnd:new Date(),traderName:user.name!,direction:'SELL',tradeScope:'INTERNATIONAL',tradeStatus:'LOCKED',submittedToExecution:true,commodityId:commodity.id,counterpartyId:cp.id,quantity:20,quantityUnit:'MT',price:1000,currency:'USD',ratePerKg:280,createdById:user.id,tradeParams:params}});
 await prisma.executionContract.create({data:{tradeId:trade.id,tradeRef:trade.tradeRef,contractDate:new Date(),direction:'SELL',executionProfile:'SALE_EX_WAREHOUSE',tradeScope:'INTERNATIONAL',incoterms:'FOB',commodityCode:'SES',commodityName:'Sesame',counterpartyName:cp.name,counterpartyCode:cp.code,quantityUnit:'MT',contractualQtyMt:20,openQtyMt:20,qualityTolerances:{},currency:'USD',traderName:user.name!,lockedAt:new Date(),lockedBy:user.name!,ratePerKg:280,executionEntity:'PAK',closeOnPayment:true}});
 const contract=()=>prisma.executionContract.findUniqueOrThrow({where:{tradeRef:trade.tradeRef}});
 const request=(entity:'PAK'|'FZCO',amountPkr=2800000)=>({tradeRef:trade.tradeRef,requestKey:randomUUID(),amountPkr,entity,actor:'Execution',userId:user.id,code:'SES'});
 const book=await sesameBook('SES');assert.equal(book.positions.find(p=>p.entity==='FZCO')!.openBuyMt,20);
 assert.equal(deskSide('SES','SELL',params,'FZCO'),'BUY');
 const fzcoContracts=await getLockedContracts({commodityCode:'SES',executionEntity:'FZCO',profile:'PURCHASE_DELIVERED'});
 assert.equal(fzcoContracts[0].direction,'BUY');assert.equal(fzcoContracts[0].counterpartyName,'Kastros Pakistan');
 const input=request('PAK');const created=await createInternalPayment(input);
 assert.equal((await createInternalPayment(input)).voucherNo,created.voucherNo);
 const voucher=await prisma.voucher.findUniqueOrThrow({where:{voucherNo:created.voucherNo}});
 assert.equal(voucher.reference,null);assert.equal(voucher.traderApprovalRequired,true);
 assert.equal((await listVouchers({commodityCode:'SES',executionEntity:'PAK'})).length,1);
 assert.equal((await listVouchers({commodityCode:'SES',executionEntity:'FZCO'})).length,1);
 assert.equal((await listVouchers({financeOnly:true,status:'PENDING_FINANCE'})).length,0);
 assert.equal((await excessAdvanceQueue(user.name!)).length,1);
 await assert.rejects(()=>createInternalPayment(request('FZCO')),/already awaiting approval/);
 await assert.rejects(()=>approveVoucher(voucher.id,'Finance',undefined,'REF1',{method:'Cash'}),/trader must approve/);
 await assert.rejects(()=>resolveExcessAdvance(voucher.id,'Another Trader',true),/Only the trade/);
 await resolveExcessAdvance(voucher.id,user.name!,true);
 assert.equal((await contract()).contractStatus,'Open');assert.equal(await prisma.counterpartyLedgerEntry.count(),0);
 assert.equal((await listVouchers({financeOnly:true,status:'PENDING_FINANCE'})).length,1);
 await assert.rejects(()=>approveVoucher(voucher.id,'Finance'),/payment reference/);
 await approveVoucher(voucher.id,'Finance',undefined,'REF1',{method:'Cash'});
 assert.equal((await contract()).contractStatus,'Open');
 const entries=await prisma.counterpartyLedgerEntry.findMany();assert.equal(entries.length,2);
 assert.ok(entries.some(e=>e.executionEntity==='PAK'&&e.side==='SELL'));
 assert.ok(entries.some(e=>e.executionEntity==='FZCO'&&e.side==='BUY'));
 assert.ok(entries.every(e=>e.sourceRef===voucher.voucherNo&&Number(e.amountPkr)===2800000));
 await assert.rejects(()=>approveVoucher(voucher.id,'Finance',undefined,'REF1',{method:'Cash'}),/already resolved/);
 await assert.rejects(()=>createInternalPayment(request('FZCO',2800001)),/exceeds/);
 // Concurrent requests from both desks create just one pending voucher.
 const race=await Promise.allSettled([createInternalPayment(request('FZCO')),createInternalPayment(request('PAK'))]);
 assert.equal(race.filter(r=>r.status==='fulfilled').length,1);
 let pending=await prisma.voucher.findFirstOrThrow({where:{status:'PENDING_FINANCE'}});
 await resolveExcessAdvance(pending.id,user.name!,false);
 assert.equal((await contract()).contractStatus,'Open');
 const final=await createInternalPayment(request('FZCO'));
 pending=await prisma.voucher.findUniqueOrThrow({where:{voucherNo:final.voucherNo}});
 await resolveExcessAdvance(pending.id,user.name!,true);
 await approveVoucher(pending.id,'Finance',undefined,'REF2',{method:'Bank transfer',bankName:'Test bank'});
 assert.equal((await contract()).contractStatus,'Close');
 assert.equal(Number((await contract()).openQtyMt),20);assert.equal(Number((await contract()).receivedQtyMt),0);
 await refreshContract(trade.tradeRef);assert.equal((await contract()).contractStatus,'Close');
 const closedBook=await sesameBook('SES');assert.equal(closedBook.positions.find(p=>p.entity==='FZCO')!.openBuyMt,0);assert.equal(closedBook.positions.find(p=>p.entity==='PAK')!.openSellMt,0);
 assert.equal((await tripartyGateTrades()).internal[0].tradeRef,trade.tradeRef);
 assert.equal(bookedPakistanSaleKgAtWarehouse({tradeRef:trade.tradeRef,direction:'SELL',tradeParams:params,quantity:20,quantityUnit:'MT',contract:{contractStatus:'Close',openQtyMt:20,quantityUnit:'MT',warehouseAllocations:[]}},'Test warehouse'),20000);
 assert.equal(await prisma.inboundReceipt.count(),0);assert.equal(await prisma.outboundDispatch.count(),0);assert.equal(await prisma.sesameOwnershipEntry.count(),0);
 assert.equal((await internalPaymentRows('SES','PAK'))[0].outstandingPkr,0);
 await assert.rejects(()=>createInternalPayment(request('PAK',1)),/exceeds/);
 await assert.rejects(()=>createInternationalPurchase({counterpartyId:cp.id,tradeRef:trade.tradeRef,amount:1,voucherDate:new Date(),entity:'FZCO',actor:'Execution',userId:user.id,code:'SES'}),/Internal Trade/);
 assert.equal(await prisma.counterpartyLedgerEntry.count(),4);
 console.log('PASS: shared voucher, retries, concurrency, Trader→Finance, paired ledgers, partial/full settlement, currency and physical stock separation.');
}
main().finally(()=>prisma.$disconnect());
